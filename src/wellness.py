def daily_advice(symptoms):
    """
    symptoms: list[str] 日常困扰描述
    返回匹配的养生条目列表（按命中词数排序），每条含 topic/advice/tcm_view/see_doctor。
    """
    if not symptoms:
        return []
    matched = []
    for item in DAILY_WELLNESS:
        hits = [kw for kw in item["keywords"] if any(kw in s for s in symptoms)]
        if hits:
            matched.append({"条目": item["topic"], "命中词": hits, **item["advice"]})
    return matched


def pretty_wellness(symptoms):
    """生成人类可读的日常养生文本（命令行用）。"""
    syms = [s for s in symptoms if s.strip()]
    if not syms:
        return "没有识别到内容，请描述你的日常困扰，例如：失眠 或 舌头有齿痕 或 手脚冰凉"
    results = daily_advice(syms)
    if not results:
        return (
            f"暂未找到针对「{'、'.join(syms)}」的日常养生条目。\n"
            "建议换个说法（如：失眠/大便不成形/眼干/腰酸），或咨询专业中医。"
        )
    lines = [f"你的困扰：{'、'.join(syms)}", ""]
    for r in results:
        lines.append(f"🌿【{r['条目']}】")
        for k, v in r.items():
            if k in ("条目", "命中词"):
                continue
            lines.append(f"  {k}：{v}")
        lines.append("")
    lines.append("⚠️ 以上为日常养生参考，不构成医疗诊断，持续不适请就医。")
    return "\n".join(lines)
