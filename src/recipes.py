# 常见同义词归一，便于匹配
_ALIASES = {
    "失眠": ["失眠", "睡不着", "入睡难", "多梦", "不寐"],
    "便秘": ["便秘", "大便干", "排便困难", "拉不出"],
    "感冒（风寒）": ["风寒感冒", "怕冷", "流清涕", "受凉感冒"],
    "感冒（风热）": ["风热感冒", "咽喉肿痛", "黄涕", "发热感冒"],
    "慢性胃炎": ["胃炎", "胃痛", "胃胀", "胃不舒服", "嗳气"],
}


def find(symptoms):
    """根据症状/困扰关键词，返回匹配的食疗方列表（按病症分组）。"""
    if not symptoms:
        return []
    matched = []
    for topic, names in _ALIASES.items():
        if any(kw in s for s in symptoms for kw in names if kw and len(kw) >= 2):
            for r in RECIPES.get(topic, []):
                matched.append({"病症": topic, **r})
    return matched
