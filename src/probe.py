def probes_for(symptoms, expanded=None, max_kw=3):
    """按用户实际说出的关键词，返回对应的追问。

    symptoms: list[str]（parse_symptoms 结果）
    expanded: 同义词展开后的集合（可选，用于"手脚发凉"命中"怕冷"这类）
    返回: [{"关键词": k, "追问": [...]}, ...]，最多 max_kw 个关键词
    """
    text = "、".join(symptoms or [])
    exp = expanded or set()
    out = []
    for kw, qs in PROBES.items():
        if kw in text or kw in exp:
            out.append({"关键词": kw, "追问": qs})
        if len(out) >= max_kw:
            break
    return out


def all_option_words():
    """所有追问选项里的词（供测试与 UI 校验）。"""
    ws = []
    for qs in PROBES.values():
        for q in qs:
            for v in q["选项"].values():
                ws.extend(v)
    return ws
