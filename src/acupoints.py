def find(text):
    """从一段文字里找出提到的穴位名（返回有序去重列表）。"""
    found = []
    for name in ACUPOINTS:
        if name in text and name not in found:
            found.append(name)
    return found


def expand(text):
    """把文本里的穴位名替换为「穴位名（定位：...；方法：...）」。"""
    for name in ACUPOINTS:
        if name in text:
            info = ACUPOINTS[name]
            text = text.replace(
                name,
                f"{name}〔定位：{info['定位']} 方法：{info['方法']}〕",
            )
    return text
