# 用于跳过识别的词（避免把普通症状误判为体质）
_SKIP = {"失眠", "多梦", "头痛", "咳嗽", "便秘", "腹泻", "恶心", "呕吐", "发热", "恶寒"}


def assess(symptoms):
    """
    symptoms: 用户描述的症状词列表（list[str]）。
    返回识别到的体质列表 [{name, matched, advice}]，按命中特征数降序。
    命中 0 个特征不返回该体质。
    """
    if not symptoms:
        return []
    # 归一化：去掉可能的""与空格
    syms = {s.strip() for s in symptoms if s and s.strip()}
    results = []
    for c in CONSTITUTIONS:
        hit = [k for k in c["key"] if k in syms]
        if hit:
            results.append({"name": c["name"], "matched": hit, "advice": c["advice"]})
    results.sort(key=lambda x: len(x["matched"]), reverse=True)
    return results


def best_constitution(symptoms):
    """返回最可能的单一体质名（命中特征最多者），无则 None。"""
    r = assess(symptoms)
    return r[0]["name"] if r else None
