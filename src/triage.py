# 通用底盘建议（任何笼统主诉都给得起，且绝对安全）
BASELINE = {
    "吃": "三餐定时、七八分饱、少冰饮与夜宵，主食里加一点粗粮。",
    "睡": "23点前躺下，睡够7小时；固定起床时间。",
    "动": "每天快走30分钟或等量活动，以微微出汗、能说话不喘为度。",
    "心": "每天留10分钟不看屏幕，做缓慢深呼吸。",
}


def detect_domains(text):
    """返回命中的域（按命中触发词数量降序）。"""
    out = []
    for d in DOMAINS:
        hits = [t for t in d["触发"] if t in text]
        if hits:
            out.append((len(hits), d, hits))
    out.sort(key=lambda x: -x[0])
    return [(d, hits) for _, d, hits in out]


def is_generic(text):
    """是否属于"说了等于没说"的笼统描述。

    先用 _clean 去掉"太/有点/很"这类程度词再判断，
    否则"不太舒服"里多了个"太"就匹配不上"不舒服"。
    """
    from .normalize import _clean
    cleaned = _clean(text or "")
    return any(w in text or w in cleaned for w in GENERIC_WORDS)


def triage(text, max_domains=2):
    """笼统输入的兜底方案。

    返回 {"笼统": bool, "域": [{名, 生活, 追问, 就医, 命中词}], "底盘": BASELINE}
    没有命中任何域时，仍返回底盘建议 + 说明。
    """
    doms = detect_domains(text)
    picks = []
    for d, hits in doms[:max_domains]:
        picks.append({
            "名": d["名"],
            "生活": d["生活"],
            "追问": d["追问"],
            "就医": d["就医"],
            "命中词": hits,
        })
    return {
        "笼统": is_generic(text),
        "域": picks,
        "底盘": BASELINE,
    }


def probe_symptom_words(domain_name):
    """某域追问里所有可选项对应的症状词（供 UI 展示/测试用）。"""
    for d in DOMAINS:
        if d["名"] == domain_name:
            words = []
            for q in d["追问"]:
                for _, vs in q["选项"].items():
                    words.extend(vs)
            return sorted(set(words))
    return []


def render_triage(t):
    """把分诊结果渲染成纯文本（命令行用）。"""
    L = []
    if t.get("笼统"):
        L.append("你这次的描述比较笼统，单凭它不足以辨证（不想凭空给你安一个证型）。")
    if t["域"]:
        L.append("")
        L.append(f"从关键词看，最相关的是：{'、'.join(d['名'] for d in t['域'])}")
