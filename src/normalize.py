# 长键优先，避免"手脚凉"里再拆出短键造成重复（重复无害，但保证稳定）
_SYN_KEYS = sorted(SYNONYMS.keys(), key=len, reverse=True)

# 口语助词/程度副词/时间词：清洗后再做子串匹配，
# 解决 "腰也酸"（≠腰酸）、"特别怕冷"、"最近总睡不着" 这类插入语导致的漏配。
# 只在"清洗后的副本"上匹配，原串也照旧匹配一遍，避免"吃一点就胀"这类键被误伤。
_STOPWORDS = [
    "有点儿", "有点", "特别", "非常", "比较", "稍微", "超级", "最近", "一直",
    "老是", "总是", "经常", "偶尔", "有时", "一直", "感觉", "觉得", "好像",
    "浑身", "全身上下",
    "也", "很", "太", "挺", "还", "都", "就", "又", "再", "总", "有些",
]

_STOP_RE = re.compile("|".join(re.escape(w) for w in sorted(_STOPWORDS, key=len, reverse=True)))


def _clean(t):
    """去掉口语助词/程度词，保留语义骨架。"""
    return _STOP_RE.sub("", t) or t


def expand_symptoms(tokens):
    """把用户 token 列表扩成标准词集合，并返回 trace：{标准词: [用户原话, ...]}。

    tokens: list[str]，来自 agent.parse_symptoms 的切分结果
    返回: (set[str] 命中用词集, dict[str, list[str]] 依据追溯)
    """
    out = set()
    trace = {}

    def _add(kw, src):
        if kw not in ALL_KEYWORDS:
            return
        out.add(kw)
        lst = trace.setdefault(kw, [])
        if src not in lst:
            lst.append(src)

    for t in tokens:
        if not t:
            continue
        # 原词 + 去助词副本，两路都匹配
        cands = [t]
        tc = _clean(t)
        if tc != t:
            cands.append(tc)
        for c in cands:
            if not c:
                continue
            # 原词直接命中（保留原有精确匹配能力）
            _add(c, t)
            # 1) 口语同义词（子串，覆盖"最近总睡不着"这类长短语）
            for slang in _SYN_KEYS:
                if slang in c:
                    for std in SYNONYMS[slang]:
                        _add(std, t)
            # 2) 知识库关键词回捞（"舌淡苔薄白" → "舌淡""苔白"）
            if len(c) >= 2:
                for kw in ALL_KEYWORDS:
                    if len(kw) >= 2 and kw != c and kw in c:
                        _add(kw, t)

    return out, trace
